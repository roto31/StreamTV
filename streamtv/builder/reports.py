"""Package reports for Channel Creator (§5.8)."""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any, Optional

from streamtv.builder.planner import dump_yaml


def _slugify(name: str) -> str:
    s = re.sub(r"[^a-zA-Z0-9]+", "-", (name or "").strip().lower()).strip("-")
    return s or "channel"


def write_channel_package(
    *,
    draft_id: str,
    channel_doc: dict[str, Any],
    schedule: dict[str, Any],
    candidates: list[dict[str, Any]],
    root: Optional[Path] = None,
    excluded: Optional[list[dict[str, Any]]] = None,
) -> dict[str, Any]:
    """Write data/builder_reports/<draft_id>/ package; return artifact paths."""
    repo = root or Path(__file__).resolve().parents[2]
    channels = channel_doc.get("channels") or []
    ch = channels[0] if channels else {}
    number = str(ch.get("number") or "0")
    name = str(ch.get("name") or "channel")
    slug = _slugify(name)
    out_dir = repo / "data" / "builder_reports" / draft_id
    out_dir.mkdir(parents=True, exist_ok=True)
    meta_dir = out_dir / "metadata"
    thumbs_dir = out_dir / "thumbnails"
    meta_dir.mkdir(exist_ok=True)
    thumbs_dir.mkdir(exist_ok=True)

    channel_yaml_name = f"channel-{number}-{slug}.yaml"
    channel_path = out_dir / channel_yaml_name
    schedule_path = out_dir / "schedules" / f"{number}.yml"
    schedule_path.parent.mkdir(parents=True, exist_ok=True)
    channel_path.write_text(dump_yaml(channel_doc), encoding="utf-8")
    schedule_path.write_text(dump_yaml(schedule), encoding="utf-8")

    urls_rows = ["id\ttype\tnetwork\tdate\truntime\turl"]
    for s in ch.get("streams") or []:
        urls_rows.append(
            "\t".join(
                [
                    str(s.get("id") or ""),
                    str(s.get("type") or ""),
                    str(s.get("network") or ""),
                    str(s.get("broadcast_date") or s.get("year") or ""),
                    str(s.get("runtime") or ""),
                    str(s.get("url") or ""),
                ]
            )
        )
    urls_path = out_dir / "urls.tsv"
    urls_path.write_text("\n".join(urls_rows) + "\n", encoding="utf-8")

    for s in ch.get("streams") or []:
        sid = str(s.get("id") or "")
        meta = s.get("source_metadata")
        if sid and isinstance(meta, dict):
            (meta_dir / f"{sid}.json").write_text(
                json.dumps(meta, indent=2) + "\n", encoding="utf-8"
            )

    sources_md = _render_sources_md(
        number=number,
        name=name,
        candidates=candidates,
        excluded=excluded or [],
    )
    sources_path = out_dir / "SOURCES.md"
    sources_path.write_text(sources_md, encoding="utf-8")

    readme_path = out_dir / "README.md"
    readme_path.write_text(
        f"# Channel {number} — {name}\n\n"
        f"Package generated by Channel Creator. See `SOURCES.md` and `urls.tsv`.\n"
        f"Install with `./install_{slug}.zsh` on another StreamTV host (number must be free).\n",
        encoding="utf-8",
    )

    install_path = out_dir / f"install_{slug}.zsh"
    install_path.write_text(
        _install_script(number=number, slug=slug, channel_yaml=channel_yaml_name),
        encoding="utf-8",
    )
    install_path.chmod(install_path.stat().st_mode | 0o111)

    artifacts = {
        "dir": str(out_dir),
        "channel_yaml": str(channel_path),
        "schedule_yaml": str(schedule_path),
        "urls_tsv": str(urls_path),
        "sources_md": str(sources_path),
        "readme": str(readme_path),
        "install_script": str(install_path),
    }
    (out_dir / "manifest.json").write_text(
        json.dumps(artifacts, indent=2) + "\n", encoding="utf-8"
    )
    return artifacts


def _render_sources_md(
    *,
    number: str,
    name: str,
    candidates: list[dict[str, Any]],
    excluded: list[dict[str, Any]],
) -> str:
    tier1: list[str] = []
    tier2: list[str] = []
    breaks: list[str] = []
    hdr = (
        "| Program | Platform | Network / station | Air date | Commercials & IDs | "
        "Format | Links (item · uploader) | Notes |\n"
        "|---|---|---|---|---|---|---|---|"
    )
    for c in candidates:
        role = c.get("role") or "program"
        plat = "archive.org" if "archive" in str(c.get("source") or "") else "YouTube"
        row = (
            f"| {c.get('title')} | {plat} | {c.get('network') or ''} | "
            f"{c.get('date') or c.get('year') or ''} | {c.get('commercials') or ''} | "
            f"{'break' if role in ('break', 'station_id') else 'program'} | "
            f"[item]({c.get('page') or c.get('url') or ''}) | {c.get('note') or ''} |"
        )
        if role in ("break", "station_id"):
            breaks.append(row)
        elif int(c.get("tier") or 2) == 1:
            tier1.append(row)
        else:
            tier2.append(row)

    excl_lines = []
    for e in excluded:
        excl_lines.append(
            f"- {e.get('title') or e.get('url') or '?'}: {e.get('reason') or ''}"
        )

    return "\n".join(
        [
            f"# {name} — StreamTV channel {number}: sources",
            "",
            "## Plain-language terms",
            "",
            "- **Off-air capture** — a home recording of the TV signal as aired.",
            "- **WOC** — with original commercials.",
            "- **Tier 1 / Tier 2** — confidence labels from the evidence classifier.",
            "",
            f"## Tier 1 — high-confidence matches ({len(tier1)})",
            "",
            hdr,
            *tier1,
            "",
            f"## Tier 2 — partial matches ({len(tier2)})",
            "",
            hdr,
            *tier2,
            "",
            "## Station-break reels used between programs",
            "",
            hdr,
            *breaks,
            "",
            "## Also found, not loaded into the channel",
            "",
            *(excl_lines or ["- (none)"]),
            "",
            "## Gaps",
            "",
            "- Recorded automatically; expand during operator review.",
            "",
        ]
    )


def _install_script(*, number: str, slug: str, channel_yaml: str) -> str:
    return f"""#!/bin/zsh
# install_{slug}.zsh — gated installer for channel {number} (§5.8 / §0.4)
emulate -L zsh
setopt pipefail
STREAMTV_HOME=${{STREAMTV_HOME:-.}}
NUMBER="{number}"
YAML="$(cd -- "$(dirname "$0")" && pwd)/{channel_yaml}"
SCHED="$(cd -- "$(dirname "$0")" && pwd)/schedules/{number}.yml"

hdr() {{ print -r -- "==> $1"; }}
ok() {{ print -r -- "  ✔ $1"; }}
fail() {{ print -r -- "  ✘ $1: $2"; exit 1; }}

hdr "1. Preflight"
[[ -f $YAML ]] || fail "YAML" "missing $YAML"
[[ -f $SCHED ]] || fail "schedule" "missing $SCHED"
ok "package present"

hdr "2. Number free (G5)"
if [[ -f $STREAMTV_HOME/data/channels_generated_$NUMBER.yaml ]] || \\
   [[ -f $STREAMTV_HOME/schedules/$NUMBER.yml ]] || \\
   [[ -f $STREAMTV_HOME/schedules/mn-olympics-$NUMBER.yml ]]; then
  fail "G5" "channel $NUMBER already present — refuse install"
fi
ok "number $NUMBER free"

hdr "3. Copy files"
cp "$YAML" "$STREAMTV_HOME/data/channels_generated_$NUMBER.yaml" || fail "copy" "channel yaml"
cp "$SCHED" "$STREAMTV_HOME/schedules/$NUMBER.yml" || fail "copy" "schedule"
ok "copied"

hdr "4. Import"
curl -fsS -X POST "http://127.0.0.1:8410/api/import/channels" \\
  -F "file=@$STREAMTV_HOME/data/channels_generated_$NUMBER.yaml" \\
  >/dev/null || fail "import" "API import failed"
ok "imported"

print -r -- "OVERALL: PASS"
"""
